// A simplified world map drawn by the app: the outlines of the land as lists of [longitude, latitude] points, and the
// maths to put them on a flat picture. The outlines are deliberately coarse (the picture is for placing a few points,
// not for navigating) and were written by hand for this app, so nothing is downloaded or licensed. This file touches
// no database code, so screens that run in the browser can import it.

/** The picture is 1000 wide; its height follows from the range of latitudes it shows. */
export const MAP_WIDTH = 1000;
const LAT_TOP = 84;
const LAT_BOTTOM = -57;
export const MAP_HEIGHT = Math.round((MAP_WIDTH * (LAT_TOP - LAT_BOTTOM)) / 360);

/** Where a longitude and latitude fall on the picture (a plain equirectangular projection). */
export function project(lon: number, lat: number): [number, number] {
  return [((lon + 180) / 360) * MAP_WIDTH, ((LAT_TOP - lat) / (LAT_TOP - LAT_BOTTOM)) * MAP_HEIGHT];
}

type Ring = [number, number][];

function path(rings: Ring[]): string {
  return rings
    .map((ring) => ring.map(([lon, lat], i) => {
      const [x, y] = project(lon, lat);
      return `${i === 0 ? "M" : "L"}${x.toFixed(1)},${y.toFixed(1)}`;
    }).join("") + "Z")
    .join("");
}

