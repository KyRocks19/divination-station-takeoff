/** Faint lines every 30 degrees, so the picture reads as a map. */
export const GRATICULE_PATH = (() => {
  const parts: string[] = [];
  for (let lon = -150; lon <= 150; lon += 30) {
    const [x1, y1] = project(lon, LAT_TOP);
    const [x2, y2] = project(lon, LAT_BOTTOM);
    parts.push(`M${x1.toFixed(1)},${y1.toFixed(1)}L${x2.toFixed(1)},${y2.toFixed(1)}`);
  }
  for (let lat = -30; lat <= 60; lat += 30) {
    const [x1, y1] = project(-180, lat);
    const [x2, y2] = project(180, lat);
    parts.push(`M${x1.toFixed(1)},${y1.toFixed(1)}L${x2.toFixed(1)},${y2.toFixed(1)}`);
  }
  return parts.join("");
})();
